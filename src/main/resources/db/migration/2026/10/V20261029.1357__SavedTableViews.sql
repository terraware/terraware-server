CREATE TABLE saved_table_views
(
  id              BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id         BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
  organization_id BIGINT REFERENCES organizations ON DELETE CASCADE,
  table_name      TEXT   NOT NULL,
  name            TEXT   NOT NULL,
  settings        JSONB  NOT NULL,
  base_view       TEXT,

  UNIQUE NULLS NOT DISTINCT (user_id, table_name, organization_id, name)
);

CREATE INDEX ON saved_table_views (organization_id);
