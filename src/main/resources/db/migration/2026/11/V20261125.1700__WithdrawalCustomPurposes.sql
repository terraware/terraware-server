CREATE TABLE withdrawal_custom_purpose_types (
    id INTEGER PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE withdrawal_custom_purposes (
    id              BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    organization_id BIGINT NOT NULL REFERENCES organizations ON DELETE CASCADE,
    type_id         INTEGER NOT NULL REFERENCES withdrawal_custom_purpose_types,
    is_archived     BOOLEAN NOT NULL DEFAULT FALSE,
    name            TEXT COLLATE case_accent_insensitive NOT NULL CHECK (length(name) > 0),
    created_by      BIGINT NOT NULL REFERENCES users,
    created_time    TIMESTAMP WITH TIME ZONE NOT NULL,
    modified_by     BIGINT NOT NULL REFERENCES users,
    modified_time   TIMESTAMP WITH TIME ZONE NOT NULL,

    UNIQUE (organization_id, type_id, name)
);

ALTER TABLE nursery.withdrawals
    ADD COLUMN custom_purpose_id BIGINT REFERENCES withdrawal_custom_purposes,
    ADD CONSTRAINT custom_purpose_only_for_other CHECK (custom_purpose_id IS NULL OR purpose_id = 4);
