CREATE TABLE restore_credentials
(
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  user_id BIGINT NOT NULL REFERENCES users ON DELETE CASCADE,
  credential_id BYTEA NOT NULL UNIQUE,
  attested_credential_data BYTEA NOT NULL,
  sign_count BIGINT NOT NULL,
  created_time TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ON restore_credentials (user_id);

CREATE TABLE restore_credential_challenges
(
  challenge BYTEA PRIMARY KEY,
  user_id BIGINT REFERENCES users ON DELETE CASCADE,
  expires_time TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ON restore_credential_challenges (user_id);
CREATE INDEX ON restore_credential_challenges (expires_time);
